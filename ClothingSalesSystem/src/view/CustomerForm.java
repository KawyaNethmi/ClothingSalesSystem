    private void loadTable() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
            new String[]{"ID","Name","Phone","Email","Address","Points"}, 0);
        java.util.List<model.Customer> list = dao.getAllCustomers();
        for (model.Customer c : list) {
            model.addRow(new Object[]{
                c.getCustomerId(), c.getCustomerName(), c.getPhone(),
                c.getEmail(), c.getAddress(), c.getLoyaltyPoints()
            });
        }
        tblCustomers.setModel(model);
    }
    
    private void clearFields() {
        txtName.setText(""); txtPhone.setText(""); txtEmail.setText("");
        txtAddress.setText(""); txtPoints.setText("0");
        selectedId = -1;
    }

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
    if (txtName.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Enter customer name");
        return;
    }
    try {
        model.Customer c = new model.Customer();
        c.setCustomerName(txtName.getText().trim());
        c.setPhone(txtPhone.getText().trim());
        c.setEmail(txtEmail.getText().trim());
        c.setAddress(txtAddress.getText().trim());
        c.setLoyaltyPoints(Integer.parseInt(txtPoints.getText().trim()));
        if (dao.addCustomer(c)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Customer added!");
            loadTable();
            clearFields();
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Points must be a number");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
    if (selectedId == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Select a row first");
        return;
    }
    try {
        model.Customer c = new model.Customer();
        c.setCustomerId(selectedId);
        c.setCustomerName(txtName.getText().trim());
        c.setPhone(txtPhone.getText().trim());
        c.setEmail(txtEmail.getText().trim());
        c.setAddress(txtAddress.getText().trim());
        c.setLoyaltyPoints(Integer.parseInt(txtPoints.getText().trim()));
        if (dao.updateCustomer(c)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Updated!");
            loadTable();
            clearFields();
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Points must be a number");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
    if (selectedId == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Select a row first");
        return;
    }
    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Delete customer?");
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        if (dao.deleteCustomer(selectedId)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Deleted!");
            loadTable();
            clearFields();
        }
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed


    private void loadStats() {
        try {
            java.sql.Connection conn = config.DBConnection.getInstance().getConnection();
            java.sql.ResultSet rs1 = conn.createStatement().executeQuery("SELECT COUNT(*) FROM product");
            if (rs1.next()) lblProductCount1.setText("Products: " + rs1.getInt(1));
            
            java.sql.ResultSet rs2 = conn.createStatement().executeQuery(
                "SELECT IFNULL(SUM(net_amount),0) FROM sales WHERE DATE(sale_date)=CURDATE()");
            if (rs2.next()) lblTodaySales1.setText("Today's Sales: " + String.format("%.2f", rs2.getDouble(1)));
            
            java.sql.ResultSet rs3 = conn.createStatement().executeQuery(
                "SELECT COUNT(*) FROM product WHERE stock_qty < 1");
            if (rs3.next()) lblLowStock1.setText("Low Stock: " + rs3.getInt(1));
        } catch (SQLException e) {}
    }
    

    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed

    String username = txtUsername.getText().trim();
    String password = new String(txtPassword.getPassword());
    
    if (username.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Enter username and password");
        return;
    }
    
    // Simple hardcoded check for now
    if (username.equals("admin") && password.equals("admin123")) {
        new DashboardForm(1, "Admin").setVisible(true);
        this.dispose();
    } else if (username.equals("cashier1") && password.equals("pass123")) {
        new DashboardForm(2, "John Silva").setVisible(true);
        this.dispose();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Invalid credentials");
    }
    
        

    }//GEN-LAST:event_btnLoginActionPerformed


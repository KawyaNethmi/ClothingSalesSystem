    private void loadCategories() {
        cmbCategory.removeAllItems();
        cmbCategory.addItem("T-Shirts");
        cmbCategory.addItem("Jeans");
        cmbCategory.addItem("Dresses");
        cmbCategory.addItem("Shirts");
        cmbCategory.addItem("Jackets");
    }
    
    private void loadTable() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
            new String[]{"ID","Name","Category","Size","Color","Price","Stock"}, 0);
        java.util.List<model.Product> list = dao.getAllProducts();
        for (model.Product p : list) {
            model.addRow(new Object[]{
                p.getProductId(), p.getProductName(), p.getCategoryName(),
                p.getSize(), p.getColor(), p.getPrice(), p.getStockQty()
            });
        }
        tblProducts.setModel(model);
    }
    
    private void clearFields() {
        txtName.setText("");
        txtSize.setText("");
        txtColor.setText("");
        txtPrice.setText("");
        txtStock.setText("");
        selectedId = -1;
    }

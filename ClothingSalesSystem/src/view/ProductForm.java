    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
    if (txtName.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Enter product name");
        return;
    }
    try {
        model.Product p = new model.Product();
        p.setProductName(txtName.getText().trim());
        p.setCategoryId(cmbCategory.getSelectedIndex() + 1);
        p.setSize(txtSize.getText().trim());
        p.setColor(txtColor.getText().trim());
        p.setPrice(Double.parseDouble(txtPrice.getText().trim()));
        p.setStockQty(Integer.parseInt(txtStock.getText().trim()));
        
        if (dao.addProduct(p)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Product added!");
            loadTable();
            clearFields();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to add");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Price and Stock must be numbers");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
    if (selectedId == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Click a row in the table first");
        return;
    }
    try {
        model.Product p = new model.Product();
        p.setProductId(selectedId);
        p.setProductName(txtName.getText().trim());
        p.setCategoryId(cmbCategory.getSelectedIndex() + 1);
        p.setSize(txtSize.getText().trim());
        p.setColor(txtColor.getText().trim());
        p.setPrice(Double.parseDouble(txtPrice.getText().trim()));
        p.setStockQty(Integer.parseInt(txtStock.getText().trim()));
        
        if (dao.updateProduct(p)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Product updated!");
            loadTable();
            clearFields();
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Price and Stock must be numbers");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
    if (selectedId == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Click a row first");
        return;
    }
    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Delete this product?");
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        if (dao.deleteProduct(selectedId)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Deleted!");
            loadTable();
            clearFields();
        }
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed


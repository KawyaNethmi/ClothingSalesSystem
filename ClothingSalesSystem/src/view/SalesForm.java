    private void btnSaveSaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveSaleActionPerformed
    if (cart.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Cart is empty");
        return;
    }
    if (pickedCustomerId == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Click a customer row first");
        return;
    }
    try {
        double total = 0;
        for (model.SaleItem item : cart) total += item.getSubtotal();
        double disc = Double.parseDouble(txtDiscount.getText().trim());
        double net = total - disc;
        String payment = txtPayment.getText().trim();
        if (payment.isEmpty()) payment = "Cash";

        int saleId = salesDao.saveSale(pickedCustomerId, userId, total, disc, net, payment, cart);
        if (saleId > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Sale saved!\nSale ID: " + saleId + "\nNet: " + String.format("%.2f", net));
            cart.clear();
            txtDiscount.setText("0");
            refreshCart();
            loadAllProducts();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to save sale");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Discount must be a number");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnSaveSaleActionPerformed


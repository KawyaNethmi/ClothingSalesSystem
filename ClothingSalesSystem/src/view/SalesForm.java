    private void btnAddToCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToCartActionPerformed
    if (pickedProductId == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Click a product row first");
        return;
    }
    try {
        int qty = Integer.parseInt(txtQty.getText().trim());
        if (qty <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Quantity must be positive");
            return;
        }
        if (qty > pickedProductStock) {
            javax.swing.JOptionPane.showMessageDialog(this, "Only " + pickedProductStock + " in stock");
            return;
        }
        model.SaleItem item = new model.SaleItem();
        item.setProductId(pickedProductId);
        item.setProductName(pickedProductName);
        item.setQuantity(qty);
        item.setUnitPrice(pickedProductPrice);
        item.setSubtotal(qty * pickedProductPrice);
        cart.add(item);
        refreshCart();
        txtQty.setText("1");
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Quantity must be a number");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnAddToCartActionPerformed


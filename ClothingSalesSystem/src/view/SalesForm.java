    private void loadAllCustomers() {
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
        new String[]{"ID","Name","Phone"}, 0);
    for (model.Customer c : customerDao.getAllCustomers()) {
        model.addRow(new Object[]{
            c.getCustomerId(), c.getCustomerName(), c.getPhone()
        });
    }
    tblCustomerPick.setModel(model);
}

private void loadAllProducts() {
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
        new String[]{"ID","Name","Size","Color","Price","Stock"}, 0);
    for (model.Product p : productDao.getAllProducts()) {
        model.addRow(new Object[]{
            p.getProductId(), p.getProductName(), p.getSize(),
            p.getColor(), p.getPrice(), p.getStockQty()
        });
    }
    tblProductPick.setModel(model);
}

private void searchCustomers() {
    String keyword = txtSearchCustomer.getText().trim().toLowerCase();
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
        new String[]{"ID","Name","Phone"}, 0);
    for (model.Customer c : customerDao.getAllCustomers()) {
        if (keyword.isEmpty() || c.getCustomerName().toLowerCase().contains(keyword)) {
            model.addRow(new Object[]{
                c.getCustomerId(), c.getCustomerName(), c.getPhone()
            });
        }
    }
    tblCustomerPick.setModel(model);
}

private void searchProducts() {
    String keyword = txtSearchProduct.getText().trim().toLowerCase();
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
        new String[]{"ID","Name","Size","Color","Price","Stock"}, 0);
    for (var p : productDao.getAllProducts()) {
        if (keyword.isEmpty() || p.getProductName().toLowerCase().contains(keyword)) {
            model.addRow(new Object[]{
                p.getProductId(), p.getProductName(), p.getSize(),
                p.getColor(), p.getPrice(), p.getStockQty()
            });
        }
    }
    tblProductPick.setModel(model);
}

private void refreshCart() {
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
        new String[]{"Product ID","Name","Qty","Unit Price","Subtotal"}, 0);
    double total = 0;
    for (model.SaleItem item : cart) {
        model.addRow(new Object[]{
            item.getProductId(), item.getProductName(),
            item.getQuantity(), item.getUnitPrice(),
            String.format("%.2f", item.getSubtotal())
        });
        total += item.getSubtotal();
    }
    tblCart.setModel(model);
    lblTotal.setText("Total: " + String.format("%.2f", total));
    updateNet();
}

private void updateNet() {
    double total = 0;
    for (model.SaleItem item : cart) total += item.getSubtotal();
    double disc = 0;
    try {
        disc = Double.parseDouble(txtDiscount.getText().trim());
    } catch (NumberFormatException e) { disc = 0; }
    lblNet.setText("Net: " + String.format("%.2f", total - disc));
}

